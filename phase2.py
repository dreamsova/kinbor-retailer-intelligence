#!/usr/bin/env python3
"""Validate reviewed research, reproduce contact ranking, and optionally check links.

No API keys, supplier files, paid calls, outreach or scraping framework required.
Facts and SKU selections are agent-reviewed CSV inputs awaiting human review, not regenerated by this script.
"""
import argparse
