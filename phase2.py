def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh',action='store_true',help='Recalculate scores/ranks and write top5_buyers.md from reviewed CSV inputs')
    parser.add_argument('--check-links',action='store_true',help='GET public source URLs and save link_checks.csv; no paid API or messages')
    parser.add_argument('--brief',action='store_true',help='Build the single-page Atlas PDF (requires reportlab and Pillow)')
    args=parser.parse_args()
    retailers,matches,evidence=read('retailers.csv'),read('sku_matches.csv'),read('evidence.csv')
    if args.refresh:refresh(retailers,matches,evidence)
    report=validate(retailers,matches,evidence)
    report['negative_controls_passed']=fault_checks(retailers,matches,evidence)
    if args.check_links:report['link_checks']=check_links(retailers,evidence)
    if args.brief:report['brief']=brief(matches)
    report['checked_at_utc']=datetime.now(timezone.utc).isoformat(timespec='seconds').replace('+00:00','Z')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
