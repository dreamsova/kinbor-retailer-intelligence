ROOT = Path(__file__).resolve().parent
DATA = ROOT / 'phase2'

def read(name):
    with (DATA / name).open(encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f))

def write(name, rows):
    with (DATA / name).open('w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)

def score(row):
    return round(10 * int(row['category_fit_0_5']) + 6 * int(row['evidence_strength_0_5'])
                 + 20 * int(row['contact_route_0_3']) / 3, 2)

def ordered(rows):
    return sorted(rows, key=lambda r: (-score(r), r['retailer_id']))

def require(condition, message):
    if not condition:
        raise ValueError(message)

def validate(retailers, matches, evidence):
    products = {p['sku']: p for p in csv.DictReader((ROOT/'products.csv').open(encoding='utf-8-sig'))}
    ids = {r['retailer_id'] for r in retailers}
    ev = {e['evidence_id']: e for e in evidence}
    require(len(retailers) == len(ids) == 20, 'Need exactly 20 unique retailer businesses')
    require(len({urlparse(r['website']).hostname.removeprefix('www.') for r in retailers}) == 20,
            'Duplicate business websites; branches must count once')
    require(len(ev) == len(evidence), 'Duplicate evidence IDs')
    for e in evidence:
        require(e['retailer_id'] in ids, 'Evidence retailer FK missing')
        u = urlparse(e['url'])
        require(u.scheme == 'https' and bool(u.hostname), 'Evidence URL must be absolute HTTPS')
        require(e['verification_status'] in ('page_read', 'search_snippet_only', 'provider_only'), 'Unknown evidence status')
        timestamp = datetime.fromisoformat(e['retrieved_at_utc'].replace('Z', '+00:00'))
        require(timestamp.tzinfo is not None, 'Retrieval timestamp must include timezone')
        require(bool(e['claim'].strip()), 'Empty evidence claim')
    counts = Counter(m['retailer_id'] for m in matches)
    require(set(counts) == ids, 'Each retailer needs SKU matches')
    require(len({(m['retailer_id'], m['sku']) for m in matches}) == len(matches), 'Duplicate match pair')
    for r in retailers:
        rid = r['retailer_id']
        require(r['country'] == 'USA' and bool(re.fullmatch(r'\d{5}', r['postal_code'])), 'US location/ZIP missing')
        require(all(r[k].strip() for k in ('address','city','state','independence_basis')), 'Missing location/independence')
        owned = [e for e in evidence if e['retailer_id'] == rid]
        require({'address','independence','category','brand'}.issubset({e['claim_type'] for e in owned}), 'Core evidence missing')
        for key in ('independence_evidence_ids','vendor_policy_evidence_ids','buyer_role_evidence_ids'):
            for eid in filter(None, r[key].split('|')):
                require(eid in ev and ev[eid]['retailer_id'] == rid, 'Retailer evidence FK missing or cross-store')
        require(3 <= counts[rid] <= 5 and counts[rid] == int(r['matched_sku_count']), 'Need 3-5 actual SKUs per store')
        for col, upper in (('category_fit_0_5',5),('evidence_strength_0_5',5),('contact_route_0_3',3)):
            require(0 <= int(r[col]) <= upper, 'Score dimension out of range')
        require(r['order_feasibility'] == 'unknown', 'No pilot buyer order feasibility was verified')
        require(float(r['contact_priority_score']) == score(r), 'Score arithmetic mismatch')
        p = int(r['contact_route_0_3'])
        if p == 3:
            require(r['vendor_policy_status'].startswith('explicit_') and any(
                e['claim_type']=='vendor_policy' and e['verification_status']=='page_read' for e in owned),
                'Explicit submission route requires page-read policy evidence')
        if p == 2:
            role_ids=list(filter(None,r['buyer_role_evidence_ids'].split('|')))
            positive=re.compile(r'\b(?:identifies|lists|names)\b.{0,90}\b(?:assistant\s+)?buyer\b',re.I)
            require(bool(role_ids) and all(ev[eid]['verification_status']=='page_read' and
                    positive.search(ev[eid]['claim']) and not re.search(r'\bno buyer\b|\bnot (?:a |the )?buyer\b',ev[eid]['claim'],re.I)
                    for eid in role_ids), 'Named buyer boost requires explicit positive, page-read role evidence')
        if r['vendor_policy_status'] == 'explicit_channel_restriction':
            require(p == 0, 'Do not boost a prohibited vendor channel')
        selected = [m for m in matches if m['retailer_id'] == rid]
        require(int(r['minimum_cartons_all_candidates']) == len(selected), 'Carton count must be per SKU')
        require(int(r['minimum_units_all_candidates']) == sum(int(m['moq_units']) for m in selected), 'Bundle units mismatch')
    for rank, r in enumerate(ordered(retailers), 1):
        require(int(r['contact_priority_rank']) == rank, 'Rank/tie-break mismatch')
    for m in matches:
        require(m['sku'] in products, 'Invented SKU / product FK missing')
        p = products[m['sku']]
        for dest, src in (('name_zh','name_zh'),('collection','collection'),('image_path','image_path'),
                          ('units_per_carton','units_per_carton'),('moq_cartons','moq_cartons'),
                          ('moq_units','moq_units'),('carton_qty_basis','carton_qty_basis'),
                          ('product_source_sheet','source_sheet'),('product_source_row','source_row')):
            require(m[dest] == p[src], f'SKU source mismatch: {m["sku"]} {dest}')
        require(int(m['moq_cartons']) == 1 and int(m['moq_units']) == int(m['units_per_carton']), 'Per-SKU carton rule violated')
        require((ROOT/m['image_path']).is_file(), 'Missing image')
        require(m['match_basis'] == 'model_inference_from_verified_category', 'Match must be labeled inference')
        require(m['order_feasibility']=='unknown' and m['commercial_status']=='research_candidate_only', 'Commercial overclaim')
        for eid in m['retailer_evidence_ids'].split('|'):
            require(eid in ev and ev[eid]['retailer_id']==m['retailer_id'], 'Match cites wrong/missing retailer')
            require(ev[eid]['claim_type'] in ('category','brand','product'), 'Match needs assortment evidence')
            require(ev[eid]['verification_status']=='page_read', 'Do not base matches on unconfirmed provider/snippet claims')
            require(m['retailer_evidence_url']==ev[eid]['url'] and m['retailer_fact']==ev[eid]['claim'], 'Match fact/provenance drift')
    for sku in ('DTB6611-1','DTB6616-1'):
        require(products[sku]['units_per_carton']=='112', 'Owner-confirmed 112-unit carton changed')
    for rows in (retailers, matches, evidence):
        require(not any(v.lstrip().startswith(('=','+','-','@')) for row in rows for v in row.values()), 'Unsafe spreadsheet formula prefix')
    manifest=json.loads((DATA/'sources/phase1_manifest.json').read_text())
    require(len(manifest['phase1_files'])==214, 'Phase 1 preservation manifest incomplete')
    for path, expected in manifest['phase1_files'].items():
        require(hashlib.sha256((ROOT/path).read_bytes()).hexdigest()==expected, 'Phase 1 file changed: '+path)
    run=json.loads((DATA/'sources/tinyfish_atlas_run.json').read_text())
    require(run['response']['status']=='completed' and run['run_id']=='98bb203b-8683-4485-8f7b-fc157e5c2a3b', 'TinyFish execution receipt missing')
    return {'retailers':len(retailers),'sku_matches':len(matches),'evidence_rows':len(evidence),
            'phase1_preserved_files':len(manifest['phase1_files']), 'checks':'passed'}

def fault_checks(retailers,matches,evidence):
    """Negative controls: exercise failures that would silently mislead a buyer."""
    cases = []
    m=copy.deepcopy(matches);m[0]['sku']='NOT-A-REAL-SKU';cases.append((retailers,m,evidence))
    m=copy.deepcopy(matches);m[0]['moq_units']='1';cases.append((retailers,m,evidence))
    m=copy.deepcopy(matches);m[0]['retailer_evidence_ids']='R20-E04';cases.append((retailers,m,evidence))
    r=copy.deepcopy(retailers);r[0]['order_feasibility']='verified';cases.append((r,matches,evidence))
    r=copy.deepcopy(retailers);r[0]['contact_route_0_3']='3';r[0]['contact_priority_score']=str(score(r[0]));cases.append((r,matches,evidence))
    # A negative mention of a buyer is not a named buyer. Recompute ranks so this
    # control tests the role-evidence guard, not a stale derived rank.
    r=copy.deepcopy(retailers)
    target=next(x for x in r if x['retailer_id']=='R10')
    target['contact_route_0_3']='2';target['buyer_role_evidence_ids']='R10-E07'
    for i,row in enumerate(ordered(r),1):row['contact_priority_score']=str(score(row));row['contact_priority_rank']=str(i)
    cases.append((r,matches,evidence))
    for args in cases:
        try: validate(*args)
        except ValueError: continue
        raise ValueError('A deliberately corrupted dataset passed validation')
    return len(cases)

def refresh(retailers,matches,evidence):
    for i,r in enumerate(ordered(retailers),1):
        r['contact_priority_score']=str(score(r));r['contact_priority_rank']=str(i)
    # Validate the complete proposed state before touching reviewable outputs.
    validate(retailers,matches,evidence)
    write('retailers.csv',retailers)
    text=['# First five contact priorities','',
          'Research shortlist for human review, not confirmed buyers. Order feasibility is **Unknown for every store**. No messages sent. Source collection: 2026-11-10 UTC (2026-11-09 in Chicago).','',
          'Score = 10 × category fit (0–5) + 6 × evidence strength (0–5) + (20/3) × contact route (0–3). See [research notes](RESEARCH_NOTES.md) for anchors and limitations. Ties sort by retailer_id, an administrative convention with no commercial meaning.','',
          '| Rank | Retailer | Category / Evidence / Contact | Score | All candidates minimum |',
          '|---|---|---|---|---|']
    for r in ordered(retailers)[:5]:
        text.append(f'| {r["contact_priority_rank"]} | [{r["name"]}]({r["website"]}) | {r["category_fit_0_5"]} / {r["evidence_strength_0_5"]} / {r["contact_route_0_3"]} | {score(r):.2f} | {r["minimum_cartons_all_candidates"]} cartons / {r["minimum_units_all_candidates"]} units |')
    for r in ordered(retailers)[:5]:
        rid=r['retailer_id'];selected=[m for m in matches if m['retailer_id']==rid]
        text += ['',f'## {r["contact_priority_rank"]}. {r["name"]}',
          f'**Location:** {r["address"]}, {r["city"]}, {r["state"]} {r["postal_code"]}.',
          f'**Why review:** {r["category_fit_reason"]}',
          f'**Route evidence:** {r["contact_route_reason"]} [Reviewed contact page]({r["contact_url"]}). '+('Policy evidence: '+r['vendor_policy_evidence_ids']+'.' if r['vendor_policy_evidence_ids'] else 'No explicit vendor submission policy verified.'),
          '**Contact constraints:** '+r['contact_constraints']+(' [Submission instructions]('+r['vendor_submission_url']+').' if r['vendor_submission_url'] else ''),
          '**Candidate SKUs:** '+', '.join(f'{m["sku"]} ({m["moq_units"]} units / carton; [{m["retailer_evidence_ids"]}]({m["retailer_evidence_url"]}))' for m in selected)+'.',
          '**Before any contact/offer:** human checks aesthetic and English usability, confirms U.S. resale authority, supplier availability, landed economics and capacity for one full carton per SKU. Ask permission to share the brief through the permitted channel; do not imply buying intent.']
    fifth=score(ordered(retailers)[4]);ties=[r['name'] for r in ordered(retailers)[5:] if score(r)==fifth]
    text += ['', '**Cutoff tie:** '+', '.join(ties)+' also score '+f'{fifth:.2f}'+'. The fifth-place position is an administrative tie-break, not evidence Atlas is more likely to buy.', '',
             'Publicly named buyers at Penny Post / The Paper Mouse are role signals; neither establishes submission acceptance. Wonder Fair discourages follow-up inquiries; Shorthand discourages unannounced sample visits. Two Hands bars vendor pitches to its web-order email and is held for route discovery. Paper Skyscraper has a submission form but weak verified notebook fit and a large sticker carton; it is not elevated just for having a form.','']
    (DATA/'top5_buyers.md').write_text('\n'.join(text),encoding='utf-8')

def check_links(retailers,evidence):
    urls={r['website'] for r in retailers}
    top={r['retailer_id'] for r in ordered(retailers)[:5]}
    urls.update(e['url'] for e in evidence if e['retailer_id'] in top and e['claim_type'] in ('address','independence','vendor_policy','contact','product'))
    def fetch(url):
        result={'url':url,'retrieved_at_utc':datetime.now(timezone.utc).isoformat(timespec='seconds').replace('+00:00','Z'),'http_status':'','final_url':'','title':'','status':'','note':''}
        try:
            with urlopen(Request(url,headers={'User-Agent':'KinborResearchMVP/1.0 (read-only link verification)'}),timeout=20) as response:
                body=response.read(350000).decode('utf-8','replace')
                result.update(http_status=response.status,final_url=response.url,status='reachable')
                title=re.search(r'<title[^>]*>(.*?)</title>',body,re.S|re.I)
                result['title']=re.sub(r'\s+',' ',title.group(1)).strip()[:180] if title else ''
                if any(t in result['title'].lower() for t in ('just a moment','access denied','attention required','404','not found')):
                    result['status']='review_needed';result['note']='HTTP success can still be challenge/error page.'
                else: result['note']='HTTP/title check only; does not prove the claim or current inventory.'
        except HTTPError as exc:result.update(http_status=exc.code,status='http_error',note=str(exc))
        except Exception as exc:result.update(status='unavailable',note=type(exc).__name__+': '+str(exc))
        return result
    with ThreadPoolExecutor(max_workers=4) as pool:results=list(pool.map(fetch,sorted(urls)))
    write('link_checks.csv',results)
    return dict(Counter(r['status'] for r in results))

